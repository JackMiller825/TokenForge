import { createWriteStream, existsSync } from 'node:fs';
import { mkdir, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import archiver from 'archiver';
import { APP_VERSION } from '../config';
import type { AnalysisResult } from './model';
import { validateBlueprint } from './schema';

export function blueprintReadme(analysis: AnalysisResult): string {
  return [
    '# TokenForge reference blueprint',
    '',
    `Schema ${analysis.schemaVersion}. Generated by TokenForge ${APP_VERSION}.`,
    '',
    `Site: ${analysis.finalUrl}`,
    `Title: ${analysis.title}`,
    `Analyzed: ${analysis.analyzedAt}`,
    '',
    'Identifiers connect project, page, section, element, and asset.',
    'Section roles with roleInferred true are observations, not confirmed labels.',
    'Animation records describe behavior seen in the browser. They are not the original source.',
    '',
    'assets/index.json lists mapped files and any Phase 1 manifest ids.',
    'screenshots/ holds desktop, tablet, and mobile captures.',
    'analysis/ holds pages, sections, the design system, the asset map, animations, interactions, and responsive notes.',
    '',
    analysis.demo ? 'This package is demo data and is not a scan of a live website.' : 'Only reuse material you are allowed to use.',
    '',
  ].join('\n');
}

export async function writeBlueprint(zipPath: string, projectDir: string, analysis: AnalysisResult): Promise<{ bytes: number; errors: string[] }> {
  const pages = analysis.pages;
  const sections = analysis.sections;
  const designSystem = analysis.designSystem;
  const assetMap = analysis.assetMap;
  const animations = analysis.animations;
  const interactions = analysis.interactions;
  const responsive = analysis.responsive;
  const screenshotFiles = analysis.screenshots.map((shot) => shot.file);
  const errors = validateBlueprint({ manifest: analysis, pages, sections, designSystem, assetMap, animations, interactions, responsive, screenshotFiles: screenshotFiles.filter((file) => existsSync(join(projectDir, file))) });
  if (errors.length) return { bytes: 0, errors };
  await mkdir(dirname(zipPath), { recursive: true });
  const archive = archiver('zip', { zlib: { level: 6 } });
  const output = createWriteStream(zipPath);
  const finished = new Promise<void>((resolve, reject) => {
    output.on('close', () => resolve());
    output.on('error', reject);
    archive.on('error', reject);
  });
  archive.pipe(output);
  const add = (name: string, value: unknown) => archive.append(JSON.stringify(value, null, 2), { name });
  archive.append(blueprintReadme(analysis), { name: 'README.md' });
  add('manifest.json', {
    schemaVersion: analysis.schemaVersion,
    generator: `TokenForge/${APP_VERSION}`,
    module: '02-reference-analyzer',
    projectId: analysis.projectId,
    url: analysis.url,
    finalUrl: analysis.finalUrl,
    title: analysis.title,
    analyzedAt: analysis.analyzedAt,
    completedAt: analysis.completedAt,
    demo: analysis.demo,
    warnings: analysis.warnings,
    links: {
      pages: analysis.pages.map((page) => page.url),
      sections: analysis.sections.map((section) => section.id),
      assets: analysis.assetMap.map((asset) => asset.id),
      manifestAssetIds: analysis.manifestAssetIds,
    },
    screenshots: analysis.screenshots,
  });
  add('assets/index.json', analysis.assetMap.map((asset) => ({
    mappingId: asset.id,
    sectionId: asset.sectionId,
    manifestAssetId: asset.manifestAssetId,
    match: asset.match,
    kind: asset.kind,
    sourceUrl: asset.sourceUrl,
    resolvedUrl: asset.resolvedUrl,
  })));
  add('analysis/pages.json', pages);
  add('analysis/sections.json', sections);
  add('analysis/design-system.json', designSystem);
  add('analysis/asset-map.json', assetMap);
  add('analysis/animations.json', animations);
  add('analysis/interactions.json', interactions);
  add('analysis/responsive.json', responsive);
  for (const shot of analysis.screenshots) {
    const file = join(projectDir, shot.file);
    if (existsSync(file)) archive.file(file, { name: shot.file.replace(/\\/g, '/') });
  }
  await archive.finalize();
  await finished;
  return { bytes: (await stat(zipPath)).size, errors: [] };
}

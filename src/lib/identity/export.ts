import { createWriteStream } from 'node:fs';
import { mkdir, stat } from 'node:fs/promises';
import { dirname } from 'node:path';
import archiver from 'archiver';
import { APP_VERSION } from '../config';
import type { AnalysisResult } from '../analyze/model';
import type { StudioDocument } from '../replace/model';
import { brandReport } from './consistency';
import { generationInput, phase5Readiness } from './readiness';
import { validateIdentityPackage } from './schema';
import type { IdentityDocument } from './model';
import { validateIdentity } from './validate';

export function identityReadme(doc: IdentityDocument): string {
  return [
    '# TokenForge identity package',
    '',
    `Schema ${doc.schemaVersion}. Generated by TokenForge ${APP_VERSION}.`,
    '',
    'identity/ is the new token website copy. It does not replace the reference blueprint.',
    'Tokenomics labels are website copy. Evidence status says whether you verified them.',
    'A Coming Soon contract is not a deployed address.',
    'Phase 3 assets are referenced by id. Their files stay in the replacement package.',
    'Phase 5 can read manifest.json and mapping/phase5-input.json.',
    '',
  ].join('\n');
}

export async function writeIdentityPackage(zipPath: string, doc: IdentityDocument, analysis: AnalysisResult | null, studio: StudioDocument | null, textAssets: { id: string; filename: string }[]): Promise<{ bytes: number; errors: string[] }> {
  const names = [
    'README.md', 'manifest.json',
    'identity/token.json', 'identity/tokenomics.json', 'identity/narrative.json', 'identity/sections.json', 'identity/links.json', 'identity/seo.json', 'identity/appearance.json',
    'reports/brand-consistency.json', 'reports/validation.json', 'mapping/phase5-input.json',
  ];
  const errors = validateIdentityPackage(doc, names);
  if (errors.length) return { bytes: 0, errors };
  await mkdir(dirname(zipPath), { recursive: true });
  const archive = archiver('zip', { zlib: { level: 6 } });
  const output = createWriteStream(zipPath);
  const finished = new Promise<void>((resolve, reject) => {
    output.on('close', () => resolve());
    output.on('error', reject);
    archive.on('error', reject);
  });
  archive.pipe(output);
  const add = (name: string, value: unknown) => archive.append(JSON.stringify(value, null, 2), { name });
  archive.append(identityReadme(doc), { name: 'README.md' });
  add('manifest.json', {
    schemaVersion: doc.schemaVersion,
    generator: `TokenForge/${APP_VERSION}`,
    module: '04-token-identity',
    projectId: doc.projectId,
    exportedAt: new Date().toISOString(),
    references: {
      phase1: 'original-manifest/phase1-manifest.json',
      phase2: 'original-manifest/phase2-blueprint-manifest.json',
      phase3ApprovedAssetIds: (studio?.mappings || []).filter((mapping) => mapping.state === 'approved').map((mapping) => mapping.manifestAssetId),
    },
    referenceTitle: doc.referenceTitle,
    referenceUrl: doc.referenceUrl,
  });
  add('identity/token.json', doc.token);
  add('identity/tokenomics.json', doc.tokenomics);
  add('identity/narrative.json', doc.narrative);
  add('identity/sections.json', doc.sections);
  add('identity/links.json', doc.links);
  add('identity/seo.json', doc.seo);
  add('identity/appearance.json', doc.appearance);
  add('reports/brand-consistency.json', brandReport(doc, textAssets));
  add('reports/validation.json', { issues: validateIdentity(doc), readiness: phase5Readiness(doc, analysis, studio, null, textAssets) });
  add('mapping/phase5-input.json', generationInput(doc, analysis, studio));
  await archive.finalize();
  await finished;
  return { bytes: (await stat(zipPath)).size, errors: [] };
}

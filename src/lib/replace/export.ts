import { createWriteStream, existsSync, readFileSync } from 'node:fs';
import { mkdir, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import archiver from 'archiver';
import { APP_VERSION } from '../config';
import type { AnalysisResult } from '../analyze/model';
import type { ScanResult } from '../types';
import { catalogFrom } from './catalog';
import { readinessReport } from './readiness';
import { validateReplacementPackage } from './schema';
import type { StudioDocument } from './model';

function folderFor(extension: string): string {
  if (['mp4', 'webm', 'mov'].includes(extension)) return 'videos';
  if (['woff', 'woff2', 'ttf', 'otf'].includes(extension)) return 'fonts';
  if (['png', 'jpg', 'jpeg', 'gif', 'webp', 'avif', 'bmp', 'ico', 'svg'].includes(extension)) return 'images';
  return 'other';
}

export function replacementReadme(studio: StudioDocument): string {
  return [
    '# TokenForge replacement package',
    '',
    `Schema ${studio.schemaVersion}. Generated by TokenForge ${APP_VERSION}.`,
    '',
    'original-manifest/ holds the Phase 1 manifest and the Phase 2 blueprint JSON.',
    'replacements/ holds uploaded source files. derived/ holds fitted variants.',
    'Original reference binaries are not copied into this package. The manifest keeps their URLs and ids.',
    'A suggested role is not a confirmed fact. Approved mappings are the ones a later phase may use.',
    'Image variants are resized, cropped, or padded. They are not generated artwork.',
    'One static mascot file does not recreate every pose, scene, or animation.',
    '',
    'Phase 4 can read token identity fields from mapping/phase4-contract.json.',
    'Phase 5 can read page structure, approved mappings, and placement rules from mapping/phase5-contract.json.',
    '',
  ].join('\n');
}

export async function writeReplacementPackage(zipPath: string, projectDir: string, studio: StudioDocument, scan: ScanResult | null, analysis: AnalysisResult | null): Promise<{ bytes: number; errors: string[] }> {
  const catalog = catalogFrom(scan, analysis);
  const readiness = readinessReport(studio, catalog);
  const filesOnDisk = [...studio.uploads, ...studio.derived].map((file) => file.relativePath).filter((relative) => existsSync(join(projectDir, relative)));
  const errors = validateReplacementPackage({ studio, readiness, filesOnDisk });
  if (errors.length) return { bytes: 0, errors };
  await mkdir(dirname(zipPath), { recursive: true });
  const archive = archiver('zip', { zlib: { level: 6 } });
  const output = createWriteStream(zipPath);
  const finished = new Promise<void>((resolve, reject) => {
    output.on('close', () => resolve());
    output.on('error', reject);
    archive.on('error', reject);
  });
  archive.pipe(output);
  const add = (name: string, value: unknown) => archive.append(JSON.stringify(value, null, 2), { name });
  archive.append(replacementReadme(studio), { name: 'README.md' });
  add('manifest.json', {
    schemaVersion: studio.schemaVersion,
    generator: `TokenForge/${APP_VERSION}`,
    module: '03-asset-replacement',
    projectId: studio.projectId,
    exportedAt: new Date().toISOString(),
    ready: readiness.ready,
    counts: { uploads: studio.uploads.length, derived: studio.derived.length, mappings: studio.mappings.length },
  });
  add('original-manifest/phase1-manifest.json', scan ?? { manifestVersion: '1.0.0', note: 'No Phase 1 scan is stored for this project.', assets: [] });
  add('original-manifest/phase2-blueprint-manifest.json', analysis ?? { schemaVersion: '2.0.0', note: 'No Phase 2 blueprint is stored for this project.' });
  add('mapping/replacement-map.json', studio.mappings);
  add('mapping/asset-roles.json', studio.roles);
  add('mapping/section-replacements.json', sectionReplacements(studio, analysis));
  add('mapping/compatibility-report.json', readiness.issues);
  add('mapping/phase4-contract.json', { module: '04-token-identity', consumes: ['mapping/asset-roles.json'], fields: ['name', 'ticker', 'network', 'contractAddress', 'supply', 'taxes', 'liquidityStatus', 'ownershipStatus', 'socials', 'copy'] });
  add('mapping/phase5-contract.json', phase5(studio, analysis));
  add('reports/readiness-report.json', readiness);
  add('reports/validation-report.json', { schemaVersion: studio.schemaVersion, errors: [], warnings: readiness.issues.filter((issue) => issue.severity === 'warn') });
  for (const upload of studio.uploads) {
    archive.append(readFileSync(join(projectDir, upload.relativePath)), { name: `replacements/${folderFor(upload.extension)}/${safeName(upload.originalFilename, upload.id, upload.extension)}` });
  }
  for (const derived of studio.derived) {
    archive.append(readFileSync(join(projectDir, derived.relativePath)), { name: `derived/images/${derived.id}.${derived.relativePath.split('.').pop()}` });
  }
  await archive.finalize();
  await finished;
  const bytes = (await stat(zipPath)).size;
  return { bytes, errors: [] };
}

function sectionReplacements(studio: StudioDocument, analysis: AnalysisResult | null) {
  return (analysis?.sections || []).map((section) => {
    const assets = (analysis?.assetMap || []).filter((asset) => asset.sectionId === section.id).map((asset) => asset.manifestAssetId || asset.id);
    return {
      sectionId: section.id,
      role: section.role,
      assets,
      mappings: studio.mappings.filter((mapping) => assets.includes(mapping.manifestAssetId)).map((mapping) => mapping.id),
    };
  });
}

function phase5(studio: StudioDocument, analysis: AnalysisResult | null) {
  return {
    module: '05-website-generator',
    schemaVersion: '3.0.0',
    pages: analysis?.pages || [],
    sections: (analysis?.sections || []).map((section) => ({ id: section.id, role: section.role, selector: section.selector })),
    designSystem: analysis?.designSystem || null,
    approvedMappings: studio.mappings.filter((mapping) => mapping.state === 'approved'),
    placement: studio.mappings.filter((mapping) => mapping.state === 'approved').map((mapping) => ({
      manifestAssetId: mapping.manifestAssetId,
      uploadId: mapping.uploadId,
      derivedId: mapping.derivedId,
      placement: mapping.placement,
      overrides: mapping.overrides,
    })),
    interactions: analysis?.interactions || [],
  };
}

function safeName(original: string, id: string, extension: string): string {
  const base = original.replace(/[^a-zA-Z0-9._-]+/g, '_').replace(/^_+/, '').slice(0, 80) || id;
  return base.toLowerCase().endsWith(`.${extension}`) ? `${id}-${base}` : `${id}-${base}.${extension}`;
}
